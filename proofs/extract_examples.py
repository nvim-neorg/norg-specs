#!/usr/bin/env python3
"""Extract every |example ... |end block from the Norg 1.0 spec.

The spec is written in Norg, so its examples are already a corpus. Nested
examples are supported: the outer block contains the inner markers as text,
and the inner block is recorded separately.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def extract(lines: list[str]) -> tuple[list[dict], list[int]]:
    examples: list[dict] = []
    stack: list[dict] = []  # {"line": int, "lines": list[str]}
    unclosed: list[int] = []

    for number, line in enumerate(lines, 1):
        stripped = line.strip()
        if stripped == "|example":
            if stack:
                # The marker is literal text in the enclosing example.
                stack[-1]["lines"].append(line)
            stack.append({"line": number, "lines": []})
        elif stripped == "|end":
            if not stack:
                continue
            block = stack.pop()
            examples.append({"line": block["line"], "text": "\n".join(block["lines"])})
            if stack:
                stack[-1]["lines"].append(line)
        else:
            for block in stack:
                block["lines"].append(line)

    unclosed = [block["line"] for block in stack]
    return examples, unclosed


def lean_string(text: str) -> str:
    """Render `text` as a Lean string literal."""
    out: list[str] = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append(f"\\u{{{ord(ch):04x}}}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def write_lean(examples: list[dict], output: Path) -> None:
    body = ",\n".join(
        f"  {{ line := {example['line']}, text := {lean_string(example['text'])} }}"
        for example in examples
    )
    output.write_text(
        "/-\n"
        "  Generated by extract_examples.py from ../1.0-specification.norg.\n"
        "  Do not edit by hand; rerun the script instead.\n"
        "-/\n"
        "namespace Norg.Corpus\n\n"
        "structure Example where\n"
        "  line : Nat\n"
        "  text : String\n"
        "  deriving Repr, DecidableEq\n\n"
        "def examples : List Example := [\n"
        f"{body}\n"
        "]\n\n"
        "end Norg.Corpus\n",
        encoding="utf-8",
    )


def main() -> int:
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "source",
        nargs="?",
        type=Path,
        default=here.parent / "1.0-specification.norg",
    )
    parser.add_argument("-o", "--output", type=Path, default=here / "examples.json")
    parser.add_argument(
        "--lean-output",
        type=Path,
        default=here / "Norg" / "Corpus.lean",
        help="also emit the examples as a Lean data module",
    )
    args = parser.parse_args()

    lines = args.source.read_text(encoding="utf-8").splitlines()
    examples, unclosed = extract(lines)
    if unclosed:
        print(f"unclosed |example blocks at lines: {unclosed}", file=sys.stderr)
        return 1
    if not examples:
        print("no examples found; the marker syntax or source path changed", file=sys.stderr)
        return 1

    args.output.write_text(
        json.dumps({"source": str(args.source), "examples": examples}, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    write_lean(examples, args.lean_output)
    print(f"wrote {len(examples)} examples to {args.output} and {args.lean_output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
