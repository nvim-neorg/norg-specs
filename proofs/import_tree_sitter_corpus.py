#!/usr/bin/env python3
"""Import the tree-sitter-norg corpus as Lean data.

The upstream corpus format is:

    ========================================================================
    Case name
    ========================================================================
    input
    ------------------------------------------------------------------------
    (document ...)

Separator lines are long runs of `=` and `-`.  The expected tree is kept in
the JSON for reference; the Lean module only needs the input and whether the
expected tree contains an ERROR/MISSING node.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def is_separator(line: str, char: str) -> bool:
    return len(line) >= 20 and set(line) == {char}


def parse_file(path: Path) -> list[dict]:
    lines = path.read_text(encoding="utf-8").splitlines()
    cases: list[dict] = []
    i = 0
    while i < len(lines):
        if not is_separator(lines[i], "="):
            i += 1
            continue

        # A case has: separator, name, separator, input..., separator, expected...
        if i + 2 >= len(lines) or not is_separator(lines[i + 2], "="):
            i += 1
            continue
        name = lines[i + 1].strip()
        i += 3

        input_lines: list[str] = []
        while i < len(lines) and not is_separator(lines[i], "-"):
            input_lines.append(lines[i])
            i += 1
        if i >= len(lines):
            break
        i += 1

        expected_lines: list[str] = []
        while i < len(lines) and not is_separator(lines[i], "="):
            expected_lines.append(lines[i])
            i += 1

        expected = "\n".join(expected_lines).strip()
        cases.append(
            {
                "file": path.name,
                "name": name,
                "input": "\n".join(input_lines) + "\n",
                "expected": expected,
                "expected_error": "(ERROR" in expected or "(MISSING" in expected,
            }
        )
    return cases


def lean_string(text: str) -> str:
    out: list[str] = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append(f"\\u{{{ord(ch):04x}}}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def write_lean(cases: list[dict], output: Path) -> None:
    body = ",\n".join(
        "  { file := "
        + lean_string(case["file"])
        + ", name := "
        + lean_string(case["name"])
        + ", input := "
        + lean_string(case["input"])
        + ", expectedError := "
        + ("true" if case["expected_error"] else "false")
        + " }"
        for case in cases
    )
    output.write_text(
        "/-\n"
        "  Generated by import_tree_sitter_corpus.py from\n"
        "  https://github.com/nvim-neorg/tree-sitter-norg/test/corpus.\n"
        "  Do not edit by hand; rerun the script instead.\n"
        "-/\n"
        "namespace Norg.TreeSitterCorpus\n\n"
        "structure Case where\n"
        "  file : String\n"
        "  name : String\n"
        "  input : String\n"
        "  expectedError : Bool\n"
        "  deriving Repr, DecidableEq\n\n"
        "def cases : List Case := [\n"
        f"{body}\n"
        "]\n\n"
        "end Norg.TreeSitterCorpus\n",
        encoding="utf-8",
    )


def main() -> int:
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "corpus",
        nargs="?",
        type=Path,
        default=Path("/tmp/opencode/tree-sitter-norg/test/corpus"),
    )
    parser.add_argument("-o", "--output", type=Path, default=here / "tree_sitter_corpus.json")
    parser.add_argument(
        "--lean-output",
        type=Path,
        default=here / "Norg" / "TreeSitterCorpus.lean",
    )
    args = parser.parse_args()

    cases: list[dict] = []
    for path in sorted(args.corpus.glob("*.txt")):
        cases.extend(parse_file(path))
    if not cases:
        raise SystemExit(f"no corpus cases found in {args.corpus}")

    args.output.write_text(
        json.dumps(cases, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    write_lean(cases, args.lean_output)
    invalid = sum(case["expected_error"] for case in cases)
    print(
        f"wrote {len(cases)} cases ({invalid} expected-error) to "
        f"{args.output} and {args.lean_output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
